/* ints.h -- 整数类型定义
 * 为 minizip 提供基本的整数类型
 */

#ifndef _INTS_H
#define _INTS_H

#include <stdint.h>

typedef uint64_t ui64_t;
typedef int64_t  i64_t;
typedef uint32_t ui32_t;
typedef int32_t  i32_t;
typedef uint16_t ui16_t;
typedef int16_t  i16_t;
typedef uint8_t  ui8_t;
typedef int8_t   i8_t;

#endif /* _INTS_H */
